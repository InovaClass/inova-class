import { createHash } from 'node:crypto'
import { mkdir, rm, writeFile } from 'node:fs/promises'

import { jsfxr, type SynthDefinition } from 'jsfxr'
import * as prettier from 'prettier'

const OUTPUT_DIR = 'public/sounds'
const PUBLIC_PATH = '/sounds'
const MANIFEST_FILE = 'src/app/helpers/sound-manifest.ts'

const { SQUARE, SAWTOOTH } = jsfxr.waveforms

// Fixed parameters instead of jsfxr's presets, which roll new values on every run. The meaning of
// each one is in the sliders of https://sfxr.me
const EFFECTS = {
  coins: {
    wave_type: SQUARE,
    p_duty: 0.5,
    p_base_freq: 0.55,
    p_env_sustain: 0.05,
    p_env_punch: 0.45,
    p_env_decay: 0.3,
    p_arp_speed: 0.6,
    p_arp_mod: 0.35
  },
  'power-up': {
    wave_type: SQUARE,
    p_duty: 0.3,
    p_base_freq: 0.3,
    p_freq_ramp: 0.25,
    p_repeat_speed: 0.55,
    p_env_sustain: 0.15,
    p_env_decay: 0.3
  },
  hurt: {
    wave_type: SAWTOOTH,
    p_duty: 1,
    p_base_freq: 0.45,
    p_freq_ramp: -0.45,
    p_env_sustain: 0.05,
    p_env_decay: 0.25,
    p_hpf_freq: 0.1
  },
  'level-up': {
    wave_type: SQUARE,
    p_duty: 0.5,
    p_base_freq: 0.3,
    p_freq_ramp: 0.1,
    p_repeat_speed: 0.35,
    p_arp_speed: 0.55,
    p_arp_mod: 0.3,
    p_env_sustain: 0.4,
    p_env_punch: 0.3,
    p_env_decay: 0.45
  },
  draw: {
    wave_type: SAWTOOTH,
    p_duty: 1,
    p_base_freq: 0.35,
    p_arp_speed: 0.5,
    p_arp_mod: 0.45,
    p_env_sustain: 0.25,
    p_env_punch: 0.5,
    p_env_decay: 0.4
  }
} satisfies Record<string, Partial<SynthDefinition>>

const OUTPUT = { sound_vol: 0.3, sample_rate: 44_100, sample_size: 8 }

// The noise waveform reads Math.random while rendering: a fixed seed keeps every run's files, and
// so their hashed names, the same
const seededRandom = (initialSeed: number) => {
  let seed = initialSeed
  return () => {
    seed = (seed * 16_807) % 2_147_483_647
    return (seed - 1) / 2_147_483_646
  }
}
Math.random = seededRandom(1)

await rm(OUTPUT_DIR, { recursive: true, force: true })
await mkdir(OUTPUT_DIR, { recursive: true })

const paths: Record<string, string> = {}
for (const [name, parameters] of Object.entries(EFFECTS)) {
  const definition = new jsfxr.Params().fromJSON({ ...parameters, ...OUTPUT })
  const content = Buffer.from(jsfxr.sfxr.toWave(definition).wav)
  const hash = createHash('sha256').update(content).digest('hex').slice(0, 10)
  const file = `${name}-${hash}.wav`
  await writeFile(`${OUTPUT_DIR}/${file}`, content)
  paths[name] = `${PUBLIC_PATH}/${file}`
}

const source = `// Generated by \`pnpm sounds:generate\` (src/infra/scripts/generate-sounds.ts): don't edit
export const SOUND_EFFECTS = ${JSON.stringify(paths)} as const

export type SoundEffect = keyof typeof SOUND_EFFECTS
`
const options = await prettier.resolveConfig(MANIFEST_FILE)
await writeFile(
  MANIFEST_FILE,
  await prettier.format(source, { ...options, filepath: MANIFEST_FILE })
)

process.stdout.write(`${Object.keys(paths).length} sounds\n`)
